// Connection facts for every provider S3 Explorer ships a preset for.
//
// GENERATED from S3Explorer-Core/src/config/providers.ts and its i18n help
// strings — the desktop app is the source of truth. Regenerate rather than
// hand-edit: the point is that what this site documents is exactly what the
// connection form fills in.
//
// Editorial content (worked examples, gotchas, prose) lives separately in
// provider-content.ts, because only providers we have genuinely written up
// get a page. A page built from these fields alone would be ~180 words of
// near-identical boilerplate across 25 URLs, which search engines read as
// doorway pages — the opposite of what we want.

